"""Computes aggregate statistics from data/dataset.csv and writes docs/findings.md (numbers only, no judgement)."""
import csv, os, os, re, io, sys, statistics
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')
os.chdir(os.path.dirname(os.path.abspath(__file__)))
rows = list(csv.DictReader(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'dataset.csv'), encoding='utf-8')))
n = len(rows)
def share(pred):
    k = sum(1 for r in rows if pred(r)); return k, round(100*k/n)
def val(r, k): return r[k].strip().lower()
no_price = share(lambda r: val(r,'price_visible_before_signup')=='no')
hybrid = share(lambda r: val(r,'pricing_model')=='hybrid')
subs = share(lambda r: val(r,'pricing_model')=='subscription')
renew_yes = share(lambda r: val(r,'auto_renewal_stated_at_checkout')=='yes')
renew_no = share(lambda r: val(r,'auto_renewal_stated_at_checkout')=='no')
renew_nobs = share(lambda r: val(r,'auto_renewal_stated_at_checkout').startswith('not observable'))
renew_norenew = share(lambda r: val(r,'auto_renewal_stated_at_checkout').startswith('stated: no renewal'))
cb = share(lambda r: val(r,'age_gate_type')=='checkbox')
dob = share(lambda r: val(r,'age_gate_type')=='date of birth')
nogate = share(lambda r: val(r,'age_gate_type')=='none')
tax_unclear = share(lambda r: val(r,'price_shown_with_tax')=='unclear')
tax_no = share(lambda r: val(r,'price_shown_with_tax')=='no')
free = share(lambda r: val(r,'free_tier_exists')=='yes')
trial = share(lambda r: val(r,'free_trial')!='none')
cancel_app = share(lambda r: 'in-app' in val(r,'cancellation_path'))
cancel_email_only = share(lambda r: 'in-app' not in val(r,'cancellation_path') and 'email' in val(r,'cancellation_path'))
eu14 = share(lambda r: '14' in r['refund_policy_stated'] and ('eu' in val(r,'refund_policy_stated') or 'withdraw' in val(r,'refund_policy_stated')))
nonref = share(lambda r: 'non-refundable' in val(r,'refund_policy_stated') or 'no refund' in val(r,'refund_policy_stated') or 'not refundable' in val(r,'refund_policy_stated') or 'final' in val(r,'refund_policy_stated'))
proc_nobs = share(lambda r: val(r,'payment_processor_visible').startswith('not observable'))
proc_named = share(lambda r: not val(r,'payment_processor_visible').startswith('not') and 'not visible' not in val(r,'payment_processor_visible'))
adult_core = share(lambda r: val(r,'adult_content_available')=='core')
eur = share(lambda r: val(r,'currency_observed').startswith('eur'))
usd = share(lambda r: val(r,'currency_observed').startswith('usd'))
lifetime = share(lambda r: 'lifetime' in val(r,'plans') or 'once' in val(r,'plans'))
weekly = share(lambda r: '/week' in val(r,'plans'))
crypto = share(lambda r: 'crypto' in val(r,'payment_methods_shown'))
discreet = share(lambda r: 'descriptor' in val(r,'notes')+val(r,'operator_name')+val(r,'payment_processor_visible') or 'discreet' in val(r,'notes') or 'bank statement' in val(r,'notes'))
cheap = []
for r in rows:
    m = re.match(r'(\d+(?:\.\d+)?) (USD|EUR)', r['cheapest_paid_monthly_equivalent'])
    cheap.append((float(m.group(1)), m.group(2), r['app_name']))
usd_vals = [c[0] for c in cheap if c[1]=='USD']; eur_vals = [c[0] for c in cheap if c[1]=='EUR']
allv = [c[0] for c in cheap]
pcts = [float(r['annual_discount_pct']) for r in rows]
cheap_sorted = sorted(cheap)
countries = {}
for r in rows:
    c = r['operator_country'].split('(')[0].split(';')[0].strip()
    countries[c] = countries.get(c, 0) + 1
def fmt(t): return f'{t[0]} of {n} ({t[1]}%)'
lines = []
lines.append('# Findings: pricing and subscription transparency of 20 AI companion apps (observed 2026-11-01)')
lines.append('')
lines.append('All figures below are computed by `scripts/findings.py` from `data/dataset.csv`. Prices are as displayed, in the currency the site showed from Belgium without a VPN. Monthly equivalents divide annual totals by 12.')
lines.append('')
lines.append('## Aggregate statistics')
lines.append('')
lines.append('| Indicator | Value |')
lines.append('|---|---|')
lines.append(f'| Apps whose prices are not visible before creating an account | {fmt(no_price)} |')
lines.append(f'| Apps using a hybrid model (subscription plus credits or tokens) | {fmt(hybrid)} |')
lines.append(f'| Apps using a pure subscription model | {fmt(subs)} |')
lines.append(f'| Apps with a free tier | {fmt(free)} |')
lines.append(f'| Apps offering a free trial of a paid plan | {fmt(trial)} |')
lines.append(f'| Median cheapest paid plan, monthly equivalent, all currencies pooled | {statistics.median(allv):.2f} (USD rows median {statistics.median(usd_vals):.2f} USD, EUR rows median {statistics.median(eur_vals):.2f} EUR) |')
lines.append(f'| Range of cheapest monthly equivalent | {min(allv):.2f} to {max(allv):.2f} |')
lines.append(f'| Median annual discount versus monthly billing | {statistics.median(pcts):.1f}% (range {min(pcts):.1f}% to {max(pcts):.1f}%) |')
lines.append(f'| Automatic renewal stated on the checkout screen | yes {fmt(renew_yes)}; no {fmt(renew_no)}; checkout states no renewal {fmt(renew_norenew)}; not observable {fmt(renew_nobs)} |')
lines.append(f'| Automatic renewal stated on checkout among the {n-renew_nobs[0]} observable checkouts | {renew_yes[0]} of {n-renew_nobs[0]} ({round(100*renew_yes[0]/(n-renew_nobs[0]))}%) |')
lines.append(f'| Age gate: simple checkbox or button | {fmt(cb)} |')
lines.append(f'| Age gate: date of birth or age bracket | {fmt(dob)} |')
lines.append(f'| Age gate: none (text statement only) | {fmt(nogate)} |')
lines.append(f'| Tax treatment unclear on price pages | {fmt(tax_unclear)} |')
lines.append(f'| Prices explicitly shown before tax | {fmt(tax_no)} |')
lines.append(f'| Cancellation possible through an in-app control | {fmt(cancel_app)} |')
lines.append(f'| Cancellation only by email or through the biller | {fmt(cancel_email_only)} |')
lines.append(f'| Terms state a non-refundable or final-sale rule | {fmt(nonref)} |')
lines.append(f'| Terms mention a 14-day EU withdrawal right | {fmt(eu14)} |')
lines.append(f'| Payment processor identifiable at checkout | {fmt(proc_named)} |')
lines.append(f'| Payment processor not observable (checkout unreachable) | {fmt(proc_nobs)} |')
lines.append(f'| Crypto accepted at checkout | {fmt(crypto)} |')
lines.append(f'| Weekly billing offered | {fmt(weekly)} |')
lines.append(f'| Lifetime or one-time plans offered | {fmt(lifetime)} |')
lines.append(f'| Adult content is the core offer | {fmt(adult_core)} |')
lines.append(f'| Prices displayed in USD | {fmt(usd)}; in EUR {fmt(eur)} |')
lines.append('')
lines.append('## Operator countries (as stated on legal pages)')
lines.append('')
for c, k in sorted(countries.items(), key=lambda x: -x[1]):
    lines.append(f'- {c}: {k}')
lines.append('')
lines.append('## Cheapest paid plan per app (monthly equivalent, as displayed)')
lines.append('')
lines.append('| App | Cheapest monthly equivalent | Annual discount |')
lines.append('|---|---|---|')
byname = {r['app_name']: r for r in rows}
for v, cur, name in cheap_sorted:
    lines.append(f'| {name} | {v:.2f} {cur} | {byname[name]["annual_discount_pct"]}% |')
lines.append('')
lines.append('## Factual observations')
lines.append('')
obs = []
obs.append(f'1. {no_price[0]} of the {n} apps show no price until an account exists: ' + ', '.join(r['app_name'] for r in rows if val(r,'price_visible_before_signup')=='no') + '.')
obs.append(f'2. {hybrid[0]} apps combine a subscription with a credit or token currency; only {subs[0]} sell a plain subscription and none sell credits alone.')
obs.append(f'3. Across the {n} apps the cheapest paid plan ranges from {min(allv):.2f} to {max(allv):.2f} per month in displayed currency, with a pooled median of {statistics.median(allv):.2f}.')
obs.append(f'4. The median annual discount is {statistics.median(pcts):.1f}% and {sum(1 for p in pcts if p>=50)} apps advertise 50% or more off for annual billing; the extremes are {min(pcts):.1f}% and {max(pcts):.1f}%.')
obs.append(f'5. Of the {n-renew_nobs[0]} checkouts that could be reached, {renew_yes[0]} state automatic renewal on the payment screen, {renew_no[0]} do not ({", ".join(r["app_name"] for r in rows if val(r,"auto_renewal_stated_at_checkout")=="no")}) and {renew_norenew[0]} states that the purchase does not renew (Kupid AI).')
obs.append(f'6. {cb[0]} apps gate age with a checkbox or button, {dob[0]} ask for a date of birth or age bracket, and {nogate[0]} rely on a sentence next to the sign-up button; Talkie offers brackets below 18 and Character.AI states a minimum age of 13.')
obs.append(f'7. Only {tax_no[0]} apps state whether displayed prices include tax; Character.AI and Janitor AI added 21% Belgian VAT at the Stripe checkout and Joi added 10.08 USD of taxes to a 47.99 USD plan.')
obs.append(f'8. {nonref[0]} apps state in their terms that payments are non-refundable or final, while {eu14[0]} mention a 14-day withdrawal right for EU consumers; Romantic AI states that the EU right does not apply and Luvr advertises a 30-day money-back guarantee in its FAQ only.')
obs.append(f'9. {crypto[0]} apps accept cryptocurrency and Kupid AI accepted only crypto or Alipay on the observation day because card payments were suspended; {weekly[0]} apps sell weekly plans and {lifetime[0]} sell lifetime or one-time access.')
obs.append(f'10. Card checkouts were unreachable for {proc_nobs[0]} apps because registration was rejected, blocked by a bot check, or the verification email arrived after the link expired; their rows keep the public pricing and terms with the reason recorded in each cell.')
lines += obs
lines.append('')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'docs', 'findings.md'), 'w', encoding='utf-8').write('\n'.join(lines))
print('\n'.join(lines))
